interface Props {
  title: string
  value: string | number
  sub?: string
  icon?: string
  trend?: { value: string; up: boolean }
  loading?: boolean
}

export function StatsCard({ title, value, sub, icon, trend, loading }: Props) {
  const iconConfig = (icon && STAT_ICONS[icon]) ? STAT_ICONS[icon] : FALLBACK_ICON

  return (
    <div className="rounded-xl border border-gray-200/80 bg-white p-5 shadow-sm ring-1 ring-gray-950/[0.03] transition-shadow hover:shadow-md">
      <div className="flex items-start justify-between gap-4">
        <div className="min-w-0 flex-1">
          <p className="text-[11px] font-semibold uppercase tracking-widest text-gray-400">
            {title}
          </p>

          {loading ? (
            <div className="mt-3 h-9 w-32 animate-pulse rounded-lg bg-gray-100" />
          ) : (
            <p className="mt-2 text-[32px] font-bold leading-none tracking-tight text-gray-900 tabular-nums">
              {value}
            </p>
          )}

          <div className="mt-2.5 flex items-center gap-2">
            {trend && !loading && (
              <span className={`inline-flex items-center gap-1 rounded-full px-2 py-0.5 text-xs font-semibold ${
                trend.up ? 'bg-green-50 text-green-700' : 'bg-red-50 text-red-600'
              }`}>
                {trend.up ? (
                  <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 12 12" fill="currentColor" className="h-2.5 w-2.5">
                    <path d="M6 2.5L10 7H2L6 2.5z" />
                  </svg>
                ) : (
                  <svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 12 12" fill="currentColor" className="h-2.5 w-2.5">
                    <path d="M6 9.5L2 5h8L6 9.5z" />
                  </svg>
                )}
                {trend.value}
              </span>
            )}
            {sub && !loading && (
              <p className="text-xs text-gray-400">{sub}</p>
            )}
          </div>
        </div>

        {icon !== undefined && (
          <div className={`flex h-11 w-11 flex-shrink-0 items-center justify-center rounded-xl ${iconConfig.bg} ${iconConfig.color} ring-1 ring-inset ring-gray-950/[0.05]`}>
            {iconConfig.svg}
          </div>
        )}
      </div>
    </div>
  )
}
